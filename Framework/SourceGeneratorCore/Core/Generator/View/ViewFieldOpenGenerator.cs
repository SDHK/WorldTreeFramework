using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using System.Collections.Generic;
using System.Text;

namespace WorldTree.SourceGenerator
{
	/// <summary>
	/// 视图字段组件挂载生成器。给每个具体 View 类型生成 ViewFieldOpen 法则，
	/// 打开时按字段名调用 ViewFieldHelp.AddView。
	/// </summary>
	public abstract class ViewFieldOpenGenerator<C> : SourceGeneratorBase<C>
		where C : ProjectGeneratorsConfig, new()
	{
		public override void Initialize(GeneratorInitializationContext context) { }

		public override void ExecuteCore(GeneratorExecutionContext context)
		{
			Compilation compilation = context.Compilation;
			INamedTypeSymbol viewType = compilation.ToINamedTypeSymbol("WorldTree.View");
			INamedTypeSymbol nodeRefType = compilation.ToINamedTypeSymbol("WorldTree.NodeRef`1");
			if (viewType == null || nodeRefType == null) return;

			foreach (TypeDeclarationSyntax typeDeclaration in NamedSymbolHelper.GetDerivedTypes(viewType, compilation))
			{
				INamedTypeSymbol type = compilation.GetSemanticModel(typeDeclaration.SyntaxTree).GetDeclaredSymbol(typeDeclaration) as INamedTypeSymbol;
				if (type == null || type.IsAbstract || type.IsGenericType) continue;

				List<IFieldSymbol> fields = CollectFields(type, viewType, nodeRefType);
				if (fields.Count == 0) continue;

				context.AddSource($"{type.Name}ViewFieldOpenRule.cs", SourceText.From(Generate(type, fields), Encoding.UTF8));
			}
		}

		/// <summary>
		/// 收集公开的 NodeRef&lt;View&gt; 字段，含基类继承的。派生字段覆盖同名基类字段。
		/// </summary>
		private static List<IFieldSymbol> CollectFields(INamedTypeSymbol type, INamedTypeSymbol viewType, INamedTypeSymbol nodeRefType)
		{
			List<IFieldSymbol> fields = new();
			HashSet<string> seen = new();
			for (INamedTypeSymbol current = type; current != null && current.SpecialType != SpecialType.System_Object; current = current.BaseType)
			{
				foreach (ISymbol member in current.GetMembers())
				{
					if (member is not IFieldSymbol field) continue;
					if (field.IsStatic || field.DeclaredAccessibility != Accessibility.Public) continue;
					if (!seen.Add(field.Name)) continue;
					if (!IsViewNodeRef(field.Type, nodeRefType, viewType)) continue;
					fields.Add(field);
				}
			}
			return fields;
		}

		private static bool IsViewNodeRef(ITypeSymbol fieldType, INamedTypeSymbol nodeRefType, INamedTypeSymbol viewType)
		{
			if (fieldType is not INamedTypeSymbol named) return false;
			if (!SymbolEqualityComparer.Default.Equals(named.OriginalDefinition, nodeRefType)) return false;
			if (named.TypeArguments.Length != 1) return false;
			if (named.TypeArguments[0] is not INamedTypeSymbol arg) return false;
			return NamedSymbolHelper.IsDerivedFrom(arg, viewType, out _);
		}

		private static string Generate(INamedTypeSymbol type, List<IFieldSymbol> fields)
		{
			string typeName = type.ToDisplayString();
			string className = $"{type.Name}ViewFieldOpenRule";
			string ns = type.ContainingNamespace == null || type.ContainingNamespace.IsGlobalNamespace
				? null
				: type.ContainingNamespace.ToDisplayString();

			StringBuilder code = new();
			code.AppendLine("// <auto-generated />");
			code.AppendLine("using WorldTree;");
			code.AppendLine();
			if (ns != null)
			{
				code.AppendLine($"namespace {ns}");
				code.AppendLine("{");
			}

			code.AppendLine($"	sealed class {className} : ViewFieldOpenRule<{typeName}>");
			code.AppendLine("	{");
			code.AppendLine($"		protected override async TreeTask Execute({typeName} self)");
			code.AppendLine("		{");
			foreach (IFieldSymbol field in fields)
			{
				code.AppendLine($"			await ViewFieldHelp.AddView(self, out self.{field.Name}, nameof(self.{field.Name}));");
			}

			code.AppendLine("		}");
			code.AppendLine("	}");
			if (ns != null) code.AppendLine("}");
			return code.ToString();
		}
	}
}
